"""Scheme B (Default): Runtime bootstrap provisioning at container startup."""

from __future__ import annotations

import json
import os
import shlex
from importlib import resources
from pathlib import Path
from typing import Any

from pokeymans.exceptions import ProvisionError
from pokeymans.models.config import PokeyConfig
from pokeymans.models.runtime import MountSpec, ProvisionResult
from pokeymans.provisioners.base import BaseProvisioner
from pokeymans.runtime.docker import DockerBackend

DEFAULT_RUNTIME_STATE_ROOT = Path.home() / ".cache" / "pokeymans" / "runtime"
CONTAINER_POKEY_DIR = "/run/pokey"


def _bash_array(name: str, values: list[str]) -> str:
    if not values:
        return f"{name}=()"
    quoted = " ".join(shlex.quote(v) for v in values)
    return f"{name}=({quoted})"


class RuntimeBootstrapProvisioner(BaseProvisioner):
    """Scheme B provisioner: runs directly on `base_image` and injects startup bootstrap."""

    def __init__(
        self,
        docker: DockerBackend | None = None,
        state_root: Path = DEFAULT_RUNTIME_STATE_ROOT,
    ) -> None:
        super().__init__(docker=docker)
        self.state_root = Path(state_root)

    def render_runtime_manifest(
        self,
        config: PokeyConfig,
        output_dir: Path,
        *,
        debug: bool = False,
        force_refresh: bool = False,
    ) -> Path:
        """Write runtime-manifest.json, runtime-config.sh, and bootstrap.sh into `output_dir`."""
        output_dir.mkdir(parents=True, exist_ok=True)

        log_mount = config.effective_log_mount()
        log_container_dir = log_mount.target if log_mount else ""
        requirements_container_path = (
            f"{CONTAINER_POKEY_DIR}/requirements.txt" if config.run.requirements_file else ""
        )

        manifest: dict[str, Any] = {
            "pod_name": config.name,
            "strategy": "runtime",
            "debug": bool(debug),
            "force_refresh": bool(force_refresh),
            "apt": list(config.run.apt),
            "apt_mirror": config.run.apt_mirror or "",
            "pip": list(config.run.pip),
            "requirements_file": requirements_container_path,
            "pip_index_url": config.run.pip_index_url or "",
            "entrypoint": config.run.entrypoint or "",
            "log_dir": log_container_dir,
        }

        manifest_path = output_dir / "runtime-manifest.json"
        manifest_path.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

        shell_lines = [
            "# Auto-generated by pokeymans RuntimeBootstrapProvisioner (Scheme B)",
            f"POKEY_POD_NAME={shlex.quote(config.name)}",
            f"POKEY_DEBUG={shlex.quote('true' if debug else 'false')}",
            f"POKEY_FORCE_REFRESH={shlex.quote('true' if force_refresh else 'false')}",
            f"POKEY_APT_MIRROR={shlex.quote(config.run.apt_mirror or '')}",
            _bash_array("POKEY_APT_PACKAGES", list(config.run.apt)),
            f"POKEY_PIP_INDEX_URL={shlex.quote(config.run.pip_index_url or '')}",
            f"POKEY_REQUIREMENTS_FILE={shlex.quote(requirements_container_path)}",
            _bash_array("POKEY_PIP_PACKAGES", list(config.run.pip)),
            f"POKEY_ENTRYPOINT={shlex.quote(config.run.entrypoint or '')}",
            f"POKEY_LOG_DIR={shlex.quote(log_container_dir)}",
        ]
        config_sh_path = output_dir / "runtime-config.sh"
        config_sh_path.write_text("\n".join(shell_lines) + "\n", encoding="utf-8")

        bootstrap_src = (
            resources.files("pokeymans.templates")
            .joinpath("bootstrap.sh")
            .read_text(encoding="utf-8")
        )
        bootstrap_path = output_dir / "bootstrap.sh"
        bootstrap_path.write_text(bootstrap_src, encoding="utf-8")
        os.chmod(bootstrap_path, 0o755)

        return manifest_path

    def prepare(
        self,
        config: PokeyConfig,
        base_image: str,
        *,
        debug: bool = False,
        force_refresh: bool = False,
    ) -> ProvisionResult:
        """Prepare Scheme B container launch inputs without building a new Docker image."""
        output_dir = (self.state_root / config.name).resolve()
        self.render_runtime_manifest(
            config,
            output_dir,
            debug=debug,
            force_refresh=force_refresh,
        )

        extra_mounts: list[MountSpec] = [
            MountSpec(
                source=str(output_dir / "bootstrap.sh"),
                target=f"{CONTAINER_POKEY_DIR}/bootstrap.sh",
                read_only=True,
            ),
            MountSpec(
                source=str(output_dir / "runtime-config.sh"),
                target=f"{CONTAINER_POKEY_DIR}/runtime-config.sh",
                read_only=True,
            ),
            MountSpec(
                source=str(output_dir / "runtime-manifest.json"),
                target=f"{CONTAINER_POKEY_DIR}/runtime-manifest.json",
                read_only=True,
            ),
        ]

        if config.run.requirements_file:
            req_path = config.resolve_path(config.run.requirements_file)
            if not req_path.is_file():
                raise ProvisionError(f"requirements_file not found: {req_path}")
            extra_mounts.append(
                MountSpec(
                    source=str(req_path),
                    target=f"{CONTAINER_POKEY_DIR}/requirements.txt",
                    read_only=True,
                )
            )

        if config.run.cache_dir:
            cache_root = config.resolve_path(config.run.cache_dir)
            apt_cache = cache_root / "apt"
            pip_cache = cache_root / "pip"
            apt_cache.mkdir(parents=True, exist_ok=True)
            pip_cache.mkdir(parents=True, exist_ok=True)
            extra_mounts.extend(
                [
                    MountSpec(source=str(apt_cache), target="/var/cache/apt/archives"),
                    MountSpec(source=str(pip_cache), target="/root/.cache/pip"),
                ]
            )

        log_mount = config.effective_log_mount()
        extra_env = {
            "POKEY_POD_NAME": config.name,
            "POKEY_MODE": "run",
            "POKEY_STRATEGY": "runtime",
            "POKEY_DEBUG": "true" if debug else "false",
            "POKEY_ENTRYPOINT": config.run.entrypoint or "",
            "POKEY_LOG_DIR": log_mount.target if log_mount else "",
            "DEBIAN_FRONTEND": "noninteractive",
        }

        return ProvisionResult(
            image=base_image,
            strategy="runtime",
            extra_mounts=extra_mounts,
            extra_env=extra_env,
            entrypoint=["/bin/bash", f"{CONTAINER_POKEY_DIR}/bootstrap.sh"],
            command=[],
        )
