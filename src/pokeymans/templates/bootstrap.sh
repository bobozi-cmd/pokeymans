#!/usr/bin/env bash
# Pokeymans Run Mode Runtime Bootstrap Script (Scheme B)
# Mounted read-only at /run/pokey/bootstrap.sh and invoked as container entrypoint.

set -euo pipefail

CONFIG_FILE="/run/pokey/runtime-config.sh"
if [[ -f "${CONFIG_FILE}" ]]; then
    # shellcheck source=/dev/null
    source "${CONFIG_FILE}"
fi

POKEY_POD_NAME="${POKEY_POD_NAME:-pod}"
POKEY_DEBUG="${POKEY_DEBUG:-false}"
POKEY_FORCE_REFRESH="${POKEY_FORCE_REFRESH:-false}"
POKEY_APT_MIRROR="${POKEY_APT_MIRROR:-}"
POKEY_PIP_INDEX_URL="${POKEY_PIP_INDEX_URL:-}"
POKEY_REQUIREMENTS_FILE="${POKEY_REQUIREMENTS_FILE:-}"
POKEY_ENTRYPOINT="${POKEY_ENTRYPOINT:-}"
POKEY_LOG_DIR="${POKEY_LOG_DIR:-}"

BOOTSTRAP_LOG=""
if [[ -n "${POKEY_LOG_DIR}" ]]; then
    if mkdir -p "${POKEY_LOG_DIR}" 2>/dev/null && [[ -w "${POKEY_LOG_DIR}" ]]; then
        BOOTSTRAP_LOG="${POKEY_LOG_DIR}/pokey-bootstrap.log"
    fi
fi

log() {
    local msg
    msg="[pokeymans $(date '+%Y-%m-%d %H:%M:%S')] $*"
    echo "${msg}"
    if [[ -n "${BOOTSTRAP_LOG}" ]]; then
        echo "${msg}" >> "${BOOTSTRAP_LOG}" || true
    fi
}

run_logged() {
    if [[ -n "${BOOTSTRAP_LOG}" ]]; then
        "$@" 2>&1 | tee -a "${BOOTSTRAP_LOG}"
    else
        "$@"
    fi
}

persist_profile_env() {
    if [[ -d /etc/profile.d ]] && [[ -w /etc/profile.d ]]; then
        {
            echo "# Auto-generated by pokeymans bootstrap"
            declare -px | grep -Ev '^declare -x (EUID|PPID|UID|BASHOPTS|SHELLOPTS|SHLVL|_|PWD|OLDPWD|HOSTNAME)=' || true
        } > /etc/profile.d/pokey_env.sh || true
    fi
}

configure_apt_mirror() {
    local mirror="${POKEY_APT_MIRROR}"
    if [[ -z "${mirror}" ]]; then
        return
    fi
    log "Configuring apt mirror: ${mirror}"
    if [[ -f /etc/apt/sources.list.d/ubuntu.sources ]]; then
        sed -i -E "s|https?://[^ ]+/ubuntu/?|${mirror}|g" /etc/apt/sources.list.d/ubuntu.sources || true
    fi
    if [[ -f /etc/apt/sources.list ]]; then
        sed -i -E "s|https?://[^ ]+/ubuntu/?|${mirror}|g" /etc/apt/sources.list || true
    fi
}

install_apt_packages() {
    if ! declare -p POKEY_APT_PACKAGES >/dev/null 2>&1; then
        return
    fi
    if (( ${#POKEY_APT_PACKAGES[@]} == 0 )); then
        return
    fi

    local missing=()
    local pkg
    for pkg in "${POKEY_APT_PACKAGES[@]}"; do
        if [[ "${POKEY_FORCE_REFRESH}" == "true" ]] || ! dpkg -s "${pkg}" >/dev/null 2>&1; then
            missing+=("${pkg}")
        fi
    done

    if (( ${#missing[@]} == 0 )); then
        log "All apt packages already installed; skipping apt-get."
        return
    fi

    configure_apt_mirror
    log "Installing apt packages: ${missing[*]}"
    export DEBIAN_FRONTEND=noninteractive
    run_logged apt-get update
    run_logged apt-get install -y --no-install-recommends "${missing[@]}"
}

install_pip_packages() {
    local has_req="false"
    local has_pkgs="false"
    if [[ -n "${POKEY_REQUIREMENTS_FILE}" ]] && [[ -f "${POKEY_REQUIREMENTS_FILE}" ]]; then
        has_req="true"
    fi
    if declare -p POKEY_PIP_PACKAGES >/dev/null 2>&1 && (( ${#POKEY_PIP_PACKAGES[@]} > 0 )); then
        has_pkgs="true"
    fi
    if [[ "${has_req}" == "false" ]] && [[ "${has_pkgs}" == "false" ]]; then
        return
    fi

    local pip_cmd=()
    if command -v python3 >/dev/null 2>&1 && python3 -m pip --version >/dev/null 2>&1; then
        pip_cmd=(python3 -m pip)
    elif command -v pip3 >/dev/null 2>&1; then
        pip_cmd=(pip3)
    elif command -v pip >/dev/null 2>&1; then
        pip_cmd=(pip)
    else
        log "ERROR: pip is not installed in the base image (add python3-pip to run.apt or base image)."
        exit 1
    fi

    local pip_args=(install)
    if [[ -z "${VIRTUAL_ENV:-}" ]] && "${pip_cmd[@]}" install --help 2>/dev/null | grep -q -- '--break-system-packages'; then
        pip_args+=(--break-system-packages)
    fi
    if [[ -n "${POKEY_PIP_INDEX_URL}" ]]; then
        pip_args+=(--index-url "${POKEY_PIP_INDEX_URL}")
    fi
    if [[ "${POKEY_FORCE_REFRESH}" == "true" ]]; then
        pip_args+=(--upgrade)
    fi

    if [[ "${has_req}" == "true" ]]; then
        log "Installing pip requirements from ${POKEY_REQUIREMENTS_FILE}"
        run_logged "${pip_cmd[@]}" "${pip_args[@]}" -r "${POKEY_REQUIREMENTS_FILE}"
    fi
    if [[ "${has_pkgs}" == "true" ]]; then
        log "Installing pip packages: ${POKEY_PIP_PACKAGES[*]}"
        run_logged "${pip_cmd[@]}" "${pip_args[@]}" "${POKEY_PIP_PACKAGES[@]}"
    fi
}

log "Starting pokeymans bootstrap for pod '${POKEY_POD_NAME}' (debug=${POKEY_DEBUG})"
persist_profile_env
install_apt_packages
install_pip_packages

if [[ "${POKEY_DEBUG}" == "true" ]]; then
    log "DEBUG mode enabled: skipping service entrypoint."
    log "Configured entrypoint (not executed): ${POKEY_ENTRYPOINT:-<none>}"
    if [[ -n "${POKEY_LOG_DIR}" ]]; then
        log "Log directory mounted at: ${POKEY_LOG_DIR}"
    fi
    exec sleep infinity
fi

if [[ -n "${POKEY_ENTRYPOINT}" ]]; then
    log "Executing service entrypoint: ${POKEY_ENTRYPOINT}"
    exec bash -lc "${POKEY_ENTRYPOINT}"
fi

log "No run.entrypoint configured; keeping container alive."
exec sleep infinity
